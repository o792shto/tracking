/** 実在の馬主の冠名など（この語で始まる名前は作らない） */
const BLOCKED_PREFIXES = ['サトノ', 'キタサン', 'メイショウ', 'ダノン', 'マイネル', 'コスモ', 'シゲル', 'アドマイヤ', 'トウカイ', 'メジロ', 'シンボリ', 'ナリタ', 'ニシノ', 'ダイワ', 'タニノ', 'アグネス', 'マチカネ', 'エイシン', 'ヒシ', 'ホッコー', 'テイエム', 'ヤマニン', 'ジャスティン', 'カシノ', 'エア'];

const MIN_LENGTH = 2;
const MAX_LENGTH = 9;

function acceptable(name: string): boolean {
  if (name.length < MIN_LENGTH || name.length > MAX_LENGTH) return false;
  if (NAME_BLOCKLIST.has(name)) return false;
  if (BLOCKED_PREFIXES.some((p) => name.startsWith(p))) return false;
  return true;
}

/** 名前を1つ作る（約9割が洋風、約1割がユーモア） */
function candidate(rng: Rng): string {
  const r = rng.next();
  if (r < 0.58) return rng.pick(HEAD) + rng.pick(TAIL);
  if (r < 0.7) return rng.pick(TAIL) + rng.pick(TAIL);
  if (r < 0.76) return rng.pick(HEAD) + rng.pick(SINGLE);
  if (r < 0.83) return rng.pick(SINGLE);
  if (r < 0.9) return 'ザ' + rng.pick(THE);
  if (r < 0.95) return rng.pick(FUNNY);
  return rng.pick(FOOD) + rng.pick(FEELING);
}

/** 架空の馬名（2〜9文字のカタカナ）。taken にある名前は使わない（同じレースで重ならないように） */
export function generateHorseName(rng: Rng, taken: ReadonlySet<string> = new Set()): string {
  for (let i = 0; i < 200; i++) {
    const name = candidate(rng);
    if (acceptable(name) && !taken.has(name)) return name;
  }
  // まず起きないが、念のため組み合わせの番号で重ならない名前にする
  for (const h of HEAD) for (const t of TAIL) if (acceptable(h + t) && !taken.has(h + t)) return h + t;
  throw new Error('馬名を作れません');
}

/** 作れる名前のおおよその数（テスト・確認用） */
export function nameVariety(): number {
  const all = new Set<string>();
  for (const h of HEAD) for (const t of TAIL) all.add(h + t);
  for (const a of TAIL) for (const b of TAIL) all.add(a + b);
  for (const h of HEAD) for (const s of SINGLE) all.add(h + s);
  for (const s of SINGLE) all.add(s);
  for (const t of THE) all.add('ザ' + t);
  for (const f of FUNNY) all.add(f);
  for (const f of FOOD) for (const g of FEELING) all.add(f + g);
  return [...all].filter(acceptable).length;
}
